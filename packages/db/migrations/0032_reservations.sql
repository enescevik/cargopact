create table reservations (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references tenants(id),
  carrier_id uuid not null references tenants(id),
  trip_id uuid not null references trips(id),
  reference text not null,
  order_number text,
  status text not null check (status in ('TASIYICI_ONAYI_BEKLIYOR','ONAYLI','DEPO_KABUL','YUKLENDI','VARISTA','TESLIM','SURESI_DOLDU','RET','IPTAL','EKSIK_HASAR','GELMEDI')),
  pallets int not null check (pallets > 0),
  gross_kg int not null check (gross_kg > 0),
  volume_m3 numeric(8,2) not null check (volume_m3 >= 0),
  product_class_id uuid not null references product_classes(id),
  unit_price_minor bigint not null check (unit_price_minor >= 0),
  total_price_minor bigint not null check (total_price_minor >= 0),
  price_breakdown jsonb not null,
  payment_plan text not null check (payment_plan in ('full','deposit')),
  deposit_percent int not null default 30,
  hold_expires_at timestamptz,
  decision_reason text,
  recipient_name text,
  pallet_codes jsonb not null default '[]'::jsonb,
  is_demo boolean not null default false,
  version int not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_reservation_reference unique (reference),
  constraint uq_reservation_order unique (order_number)
)
