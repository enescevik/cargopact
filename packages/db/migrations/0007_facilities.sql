create table facilities (
  id uuid primary key default gen_random_uuid(),
  carrier_id uuid not null references tenants(id),
  code text not null,
  name text not null,
  kind text not null check (kind in ('transfer_center','distribution_center','both')),
  city text not null,
  district text,
  address text not null,
  latitude numeric(9,6),
  longitude numeric(9,6),
  timezone text not null default 'Europe/Istanbul',
  opening_hours jsonb not null,
  intake_window jsonb,
  pickup_window jsonb,
  daily_slot_limit int check (daily_slot_limit > 0),
  contact_name text,
  contact_phone text,
  status text not null default 'active' check (status in ('active','inactive')),
  version int not null default 1,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_facility_code unique (carrier_id, code)
)
